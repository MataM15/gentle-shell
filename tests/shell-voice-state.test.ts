test('actual publisher events reach the receiver, clear on idle, and reject stale sessions', t => {
 const listeners=new Map<string,(value:unknown)=>void>();
 const events={on:(name:string,fn:(value:unknown)=>void)=>{listeners.set(name,fn);return ()=>listeners.delete(name);},emit:(name:string,value:unknown)=>listeners.get(name)?.(value)};
 let session='one'; let renders=0;
 const tui={mode:'fullscreen',terminal:{columns:160},requestRender(){renders++;}} as unknown as TUI;
 const receiver=createVoiceReceiver(events,()=>session,()=>tui.requestRender());
 const ctx={sessionManager:{getSessionId:()=>session}} as unknown as ExtensionContext;
 const publisher=createVoiceStatePublisher({events} as unknown as Pick<ExtensionAPI,'events'>,ctx);
 t.after(()=>receiver.dispose());
 assert.equal(receiver.current(), undefined, 'no state before the first event');
 publisher.publish('preparing'); assert.equal(receiver.current(), 'preparing');
 publisher.publish('listening'); assert.equal(receiver.current(), 'listening');
 publisher.publish('transcribing'); assert.equal(receiver.current(), 'transcribing');
 publisher.publish('idle'); assert.equal(receiver.current(), undefined, 'idle clears the indicator');
 publisher.publish('listening'); assert.equal(receiver.current(), 'listening');
 session='two'; assert.equal(receiver.current(), undefined, 'a replacement session starts empty');
 const rendersBefore=renders;
 publisher.publish('preparing'); assert.equal(receiver.current(), undefined, 'old session cannot update replacement');
 assert.equal(renders, rendersBefore, 'a rejected update never asks for a render');
 receiver.reset(); publisher.close();
});
test('accept only exact schema and active session, including idle clear', () => {
 const event={schema:'gentle-pi.voice-state/v1',sessionId:'here',state:'listening'};
 assert.equal(acceptedVoiceState('here',event),'listening');
 assert.equal(acceptedVoiceState('here',{...event,state:'idle'}),'idle');
 assert.equal(acceptedVoiceState('elsewhere',event),undefined);
 assert.equal(acceptedVoiceState(undefined,event),undefined);
 assert.equal(acceptedVoiceState('',{...event,sessionId:''}),undefined);
 assert.equal(acceptedVoiceState('here',{...event,state:'recording'}),undefined);
 assert.equal(acceptedVoiceState('here',{...event,extra:'no'}),undefined);
 assert.equal(acceptedVoiceState('here',{...event,schema:'wrong'}),undefined);
 assert.equal(acceptedVoiceState('here',null),undefined);
});
