import assert from 'node:assert/strict';
import test from 'node:test';
import { acceptedVoiceState, createVoiceReceiver } from '../lib/shell-voice-state.ts';
import { createVoiceStatePublisher } from '../lib/voice-status-event.ts';
import type { ExtensionAPI, ExtensionContext } from '@earendil-works/pi-coding-agent';
import type { TUI } from '@earendil-works/pi-tui';
import { renderLayoutFrame } from '@earendil-works/pi-tui/dist/layout.js';
import { installSidebar } from '../lib/shell-sidebar-layout.ts';
import { sidebarHeader, sidebarPart } from '../lib/shell-sidebar.ts';
test('actual publisher events reach pinned layout, clear on idle, and reject stale sessions', t => {
 const listeners=new Map<string,(value:unknown)=>void>();
 const events={on:(name:string,fn:(value:unknown)=>void)=>{listeners.set(name,fn);return ()=>listeners.delete(name);},emit:(name:string,value:unknown)=>listeners.get(name)?.(value)};
 let session='one'; const root={render:()=>[],invalidate(){},[Symbol.for('@earendil-works/pi-tui/layout-node')]:()=>({type:'vstack',entries:[]})};
 const tui={mode:'fullscreen',terminal:{columns:160},layoutRoot:root,requestRender(){}} as unknown as TUI;
 const receiver=createVoiceReceiver(events,()=>session,()=>tui.requestRender());
 const ctx={sessionManager:{getSessionId:()=>session}} as unknown as ExtensionContext;
 const publisher=createVoiceStatePublisher({events} as unknown as Pick<ExtensionAPI,'events'>,ctx);
 sidebarHeader(tui,{digest:()=> 'model',render:()=>['MODEL'],invalidate(){}});
 sidebarPart(tui,'agents',{digest:()=> 'agents',render:()=>['AGENTS'],invalidate(){}});
 sidebarPart(tui,'voice',{digest:()=>receiver.current() ?? '',render:()=>receiver.current() ? [`Voice · ${receiver.current()}`] : [],invalidate(){}});
 t.after(installSidebar(tui,{fg:(_c,s)=>s,bold:s=>s},()=> 'auto',()=> 'top',undefined,undefined,{tabs:true}));
 t.after(()=>receiver.dispose()); const frame=()=>renderLayoutFrame(root,160,20,()=>{}).lines.join('\n');
 assert.doesNotMatch(frame(),/Voice ·/);
 publisher.publish('preparing'); assert.match(frame(),/Voice · preparing/);
 publisher.publish('listening'); assert.match(frame(),/Voice · listening/);
 publisher.publish('transcribing'); assert.match(frame(),/Voice · transcribing/);
 publisher.publish('idle'); assert.doesNotMatch(frame(),/Voice ·/);
 publisher.publish('listening'); session='two'; assert.doesNotMatch(frame(),/Voice ·/);
 publisher.publish('preparing'); assert.doesNotMatch(frame(),/Voice ·/, 'old session cannot update replacement');
 receiver.reset(); publisher.close();
});
test('accept only exact schema and active session, including idle clear', () => {
 const event={schema:'gentle-pi.voice-state/v1',sessionId:'here',state:'listening'};
 assert.equal(acceptedVoiceState('here',event),'listening');
 assert.equal(acceptedVoiceState('here',{...event,state:'idle'}),'idle');
 assert.equal(acceptedVoiceState('elsewhere',event),undefined);
 assert.equal(acceptedVoiceState(undefined,event),undefined);
 assert.equal(acceptedVoiceState('',{...event,sessionId:''}),undefined);
 assert.equal(acceptedVoiceState('here',{...event,state:'recording'}),undefined);
 assert.equal(acceptedVoiceState('here',{...event,extra:'no'}),undefined);
 assert.equal(acceptedVoiceState('here',{...event,schema:'wrong'}),undefined);
 assert.equal(acceptedVoiceState('here',null),undefined);
});
